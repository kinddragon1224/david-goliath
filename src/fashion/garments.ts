/** 옷본 모양. 단위 상자(0~1) 안의 닫힌 선. 다리미·가위질이 같이 쓴다. */

export type Pt = [number, number];

export type Garment = {
  name: string;
  /** 위브온 중촌 청년 디자이너 브랜드(룩북 기준). */
  brand?: string;
  /** 룩북 실제 사진(public/brand/<photo>.webp). */
  photo?: string;
  /** 사진에 같이 찍힌 마네킹 목·받침 자리(위 가운데 타원 반지름, 사진 폭·높이 비율). 몸에 입힐 때 지운다. */
  neck?: [number, number];
  /** 피날레에 입힐 때: 상의·하의는 한 벌로 겹쳐 입고, whole(원피스류)은 혼자. */
  kind?: "top" | "bottom" | "whole";
  /** 너비/높이 비율. */
  aspect: number;
  color: string;
  shade: string;
  pts: Pt[];
};

/** 타원 호 위의 점들. a0→a1(라디안), n개. */
function arc(
  cx: number,
  cy: number,
  rx: number,
  ry: number,
  a0: number,
  a1: number,
  n: number,
): Pt[] {
  const out: Pt[] = [];
  for (let i = 0; i <= n; i++) {
    const a = a0 + ((a1 - a0) * i) / n;
    out.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return out;
}

/** 물결 밑단. */
function wave(x0: number, x1: number, y: number, amp: number, waves: number, n: number): Pt[] {
  const out: Pt[] = [];
  for (let i = 0; i <= n; i++) {
    const k = i / n;
    out.push([x0 + (x1 - x0) * k, y + Math.sin(k * Math.PI * 2 * waves) * amp]);
  }
  return out;
}

